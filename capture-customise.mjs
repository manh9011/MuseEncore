import { chromium } from 'playwright-core'
import { PNG } from 'pngjs'
import pixelmatch from 'pixelmatch'
import { readFileSync, writeFileSync } from 'node:fs'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
for (const [name, port] of [['react', 5180], ['vue', 5174]]) {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 })
  await page.route('http://scores.test/**', route => route.fulfill({ path: 'mscz-test-files/Chopin_-_Nocturne_Op_9_No_2_E_Flat_Major.mscz', headers: { 'access-control-allow-origin': '*' } }))
  await page.addInitScript(() => localStorage.setItem('musescoreweb:settings', JSON.stringify({ project: { migration: { Pre_3_6: { appVersion: 470, isApplyMigration: false, isAskAgain: false }, Ver_3_6: { appVersion: 470, isApplyMigration: false, isAskAgain: false } } } })))
  await page.goto(`${port===5180?'http://[::1]':'http://127.0.0.1'}:${port}/?url=http://scores.test/test.mscz`)
  const trigger = page.getByRole('button', { name: 'Customize toolbar' })
  await trigger.waitFor({ timeout: 30000 })
  await page.waitForTimeout(10000)
  await trigger.click()
  const popup = page.locator('.customise-popup')
  await popup.waitFor()
  console.log(name, await popup.boundingBox(), 'items', await popup.locator('[role=option]').count())
  await page.screenshot({ path: `customise-${name}.png` })
  const option = popup.locator('[data-action="pad-note-64"]')
  const checkbox = option.locator('input[type=checkbox]')
  const button = page.locator('.dock-top button[data-action="pad-note-64"]')
  assert.equal(await checkbox.isChecked(), true)
  assert.equal(await button.count(), 1)
  await checkbox.click()
  assert.equal(await checkbox.isChecked(), false)
  assert.equal(await button.count(), 0)
  await checkbox.click()
  assert.equal(await button.count(), 1)
  const options=popup.locator('[role=option]');const original=await options.evaluateAll(es=>es.map(e=>e.getAttribute('data-action')))
  await options.nth(1).click();await popup.getByRole('button',{name:'Move up'}).click()
  assert.equal(await options.first().getAttribute('data-action'),original[1])
  await popup.getByRole('button',{name:'Add separator line'}).click()
  assert.equal(await options.count(), original.length + 1)
  await popup.getByRole('button',{name:'Delete',exact:true}).click()
  assert.equal(await options.count(), original.length)
  await popup.getByRole('button',{name:'Reset',exact:true}).click()
  assert.deepEqual(await options.evaluateAll(es=>es.map(e=>e.getAttribute('data-action'))),original)
  await options.first().focus();await page.keyboard.press('Space')
  assert.equal(await options.first().locator('input').isChecked(),false)
  await options.first().focus();await page.keyboard.press('Space');assert.equal(await options.first().locator('input').isChecked(),true)
  await popup.locator('[role=option]').first().focus()
  await page.keyboard.press('Escape')
  assert.equal(await popup.count(), 0)
  assert.equal(await trigger.evaluate(e => document.activeElement === e), true)
  await trigger.click()
  await popup.waitFor()
  await page.mouse.click(400, 50)
  assert.equal(await popup.count(), 0)
  console.log(name, 'toggle, keyboard, reorder, separator add/delete, reset, Escape focus and outside click passed')
  await page.close()
}
await browser.close()
const a = PNG.sync.read(readFileSync('customise-react.png')), b = PNG.sync.read(readFileSync('customise-vue.png'))
const diff = new PNG({ width: a.width, height: a.height })
console.log('different pixels', pixelmatch(a.data, b.data, diff.data, a.width, a.height, { threshold: 0.1 }))
writeFileSync('customise-diff.png', PNG.sync.write(diff))
