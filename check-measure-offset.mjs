import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  for (const [name, host] of [['react', '[::1]:5180'], ['vue', '127.0.0.1:5174']]) {
    const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
    await page.route('http://scores.test/**', route => route.fulfill({ path: 'mscz-test-files/Chopin_-_Nocturne_Op_9_No_2_E_Flat_Major.mscz', headers: { 'access-control-allow-origin': '*' } }))
    await page.addInitScript(() => localStorage.setItem('musescoreweb:settings', JSON.stringify({ project: { migration: { Pre_3_6: { appVersion: 470, isApplyMigration: false, isAskAgain: false }, Ver_3_6: { appVersion: 470, isApplyMigration: false, isAskAgain: false } } } })))
    await page.goto(`http://${host}/?url=http://scores.test/test.mscz`)
    await page.waitForSelector('.page canvas')
    await page.waitForTimeout(10000)
    await page.getByRole('menuitem', { name: 'Format', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Style…', exact: true }).click()
    await page.getByRole('option', { name: 'Measure numbers', exact: true }).click()
    const range = page.locator('fieldset').filter({has:page.getByText('Measure number range at multimeasure rests',{exact:true})})
    const rangeToggle = page.getByRole('switch',{name:'Show measure number ranges'})
    if (await rangeToggle.isChecked()) await page.getByText('Show measure number ranges',{exact:true}).click()
    assert.equal(await range.locator('button').filter({hasText:'Brackets'}).isDisabled(),true)
    await page.getByText('Show measure number ranges',{exact:true}).click()
    assert.equal(await range.locator('button').filter({hasText:'Brackets'}).isEnabled(),true)
    await range.getByRole('radio',{name:'Parentheses'}).click()
    await range.getByRole('radio',{name:'Above',exact:true}).click()
    await page.getByRole('radio',{name:'Every',exact:true}).check()
    const frequency = page.getByRole('textbox',{name:'Every'})
    await frequency.fill('4')
    await frequency.press('Enter')
    await page.getByRole('radio',{name:'On all staves'}).check()
    const below = page.locator('fieldset').filter({has:page.locator('legend').getByText('Position',{exact:true})}).getByRole('radio',{name:'Below',exact:true})
    await below.click()
    assert.equal(await below.getAttribute('aria-checked'),'true')
    await page.locator('.es-qml select').first().selectOption({ label: 'Measure number (alternate)' })
    const inputs = name === 'react' ? page.locator('.es-qml input[type=text]:not([aria-label])') : page.locator('.es-qml .sd-xy-controller input[type=text]')
    assert.deepEqual(await inputs.evaluateAll(elements => elements.slice(0, 4).map(e => Number(e.value))), [0, -4, 0, 4])
    await inputs.first().fill('101')
    await inputs.first().press('Enter')
    assert.equal(Number(await inputs.first().inputValue()), 100)
    await inputs.first().fill('2')
    await inputs.first().press('Enter')
    await inputs.first().press('ArrowUp')
    assert.equal(Number(await inputs.first().inputValue()), 2.1)
    await page.getByRole('button', { name: 'OK', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Format', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Style…', exact: true }).click()
    await page.getByRole('option', { name: 'Measure numbers', exact: true }).click()
    assert.equal(Number(await inputs.first().inputValue()), 2.1)
    assert.equal(await below.getAttribute('aria-checked'),'true')
    assert.equal(await page.getByRole('radio',{name:'Every',exact:true}).isChecked(),true)
    assert.equal(await frequency.inputValue(),'4')
    assert.equal(await range.getByRole('radio',{name:'Parentheses'}).getAttribute('aria-checked'),'true')
    assert.equal(await range.getByRole('radio',{name:'Above',exact:true}).getAttribute('aria-checked'),'true')
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    console.log(`${name}: alternate offsets match`)
    await page.close()
  }
} finally { await browser.close() }
