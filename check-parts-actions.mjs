import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
try {
 for(const [name,host] of [['react','[::1]:5180'],['vue','127.0.0.1:5174']]) {
  const page=await browser.newPage({viewport:{width:1280,height:800}})
  await page.route('http://scores.test/**',r=>r.fulfill({path:'mscz-test-files/Chopin_-_Nocturne_Op_9_No_2_E_Flat_Major.mscz',headers:{'access-control-allow-origin':'*'}}))
  await page.addInitScript(()=>localStorage.setItem('musescoreweb:settings',JSON.stringify({project:{migration:{Pre_3_6:{appVersion:470,isApplyMigration:false,isAskAgain:false},Ver_3_6:{appVersion:470,isApplyMigration:false,isAskAgain:false}}}})))
  await page.goto(`http://${host}/?url=http://scores.test/test.mscz`);await page.waitForSelector('.page canvas');await page.waitForTimeout(10000)
  await page.locator('[data-action="parts"]').click();const dialog=page.locator('dialog[open]').last();const before=await dialog.getByRole('option').count()
  await dialog.getByRole('button',{name:'Create new part'}).click();const input=dialog.locator('.part-title-edit input');await input.fill('Test part');await input.press('Enter')
  assert.equal(await dialog.getByRole('option').count(),before+1)
  const row=dialog.getByRole('option').filter({hasText:'Test part'});await row.getByRole('button',{name:'Test part'}).click();await page.getByRole('menuitem',{name:'Rename'}).click()
  await dialog.locator('.part-title-edit input').fill('Renamed part');await page.keyboard.press('Escape')
  assert.equal(await dialog.getByRole('option').filter({hasText:'Renamed part'}).count(),0)
  await row.getByRole('button',{name:'Test part'}).click();await page.getByRole('menuitem',{name:'Rename'}).click()
  await dialog.locator('.part-title-edit input').fill('Renamed part');await page.keyboard.press('Enter')
  const renamed=dialog.getByRole('option').filter({hasText:'Renamed part'});await renamed.getByRole('button',{name:'Renamed part'}).click();await page.getByRole('menuitem',{name:'Duplicate'}).click()
  assert.equal(await dialog.getByRole('option').count(),before+2)
  await renamed.getByRole('button',{name:'Renamed part',exact:true}).click();await page.getByRole('menuitem',{name:'Delete'}).click()
  assert.equal(await dialog.getByRole('option').count(),before+1)
  const copy=dialog.getByRole('option').filter({hasText:'Renamed part (copy)'})
  await copy.click();await dialog.getByRole('button',{name:'Open selected'}).click()
  assert.equal(await dialog.count(),0)
  assert.equal(await page.getByText('Renamed part (copy)',{exact:true}).count()>0,true)
  await page.locator('[data-action="parts"]').click()
  const reopened=page.locator('dialog[open]').last()
  const openedCopy=reopened.getByRole('option').filter({hasText:'Renamed part (copy)'})
  await openedCopy.getByRole('button',{name:'Renamed part (copy)',exact:true}).click()
  assert.equal(await page.getByRole('menuitem',{name:'Reset'}).isEnabled(),true)
  await page.getByRole('menuitem',{name:'Reset'}).click()
  const question=page.locator('dialog[open]').last()
  if(await question.getByRole('button',{name:'Yes',exact:true}).count()) await question.getByRole('button',{name:'Yes',exact:true}).click()
  const titles=await reopened.locator('.part-title').allTextContents()
  await reopened.getByRole('button',{name:'Open all'}).click()
  assert.equal(await page.locator('dialog[open]').count(),0)
  for(const title of titles) assert.ok(await page.getByText(title,{exact:true}).count()>0, `missing opened part ${title}`)
  console.log(`${name}: create, rename, duplicate, delete, open selected/all pass`);await page.close()
 }
} finally {await browser.close()}
