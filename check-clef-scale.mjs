import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
try {
  for (const [name, host] of [['react','[::1]:5180'],['vue','127.0.0.1:5174']]) {
    const page = await browser.newPage({ viewport: { width:1280,height:800 } })
    await page.route('http://scores.test/**', route => route.fulfill({path:'mscz-test-files/Chopin_-_Nocturne_Op_9_No_2_E_Flat_Major.mscz',headers:{'access-control-allow-origin':'*'}}))
    await page.addInitScript(() => localStorage.setItem('musescoreweb:settings',JSON.stringify({project:{migration:{Pre_3_6:{appVersion:470,isApplyMigration:false,isAskAgain:false},Ver_3_6:{appVersion:470,isApplyMigration:false,isAskAgain:false}}}})))
    await page.goto(`http://${host}/?url=http://scores.test/test.mscz`)
    await page.waitForSelector('.page canvas'); await page.waitForTimeout(10000)
    await page.getByRole('menuitem',{name:'Format',exact:true}).click(); await page.getByRole('menuitem',{name:'Style…',exact:true}).click()
    await page.getByRole('option',{name:'Clefs, key & time signatures',exact:true}).click()
    const group=page.locator('fieldset').filter({has:page.locator('legend').getByText('Style and size',{exact:true})})
    const inputs=name==='react'?group.getByRole('textbox',{name:'Scale:'}):group.locator('input[type=number]').first().locator('..').locator('..').locator('input[type=number]')
    await inputs.first().fill('0.5'); if(name==='react') await inputs.first().press('Enter'); else await inputs.first().blur()
    assert.deepEqual(await inputs.evaluateAll(es=>es.map(e=>Number(e.value))),[1,1])
    await inputs.first().fill('1.5'); if(name==='react') await inputs.first().press('Enter'); else await inputs.first().blur()
    assert.deepEqual(await inputs.evaluateAll(es=>es.map(e=>Number(e.value))),[1.5,1.5])
    await page.getByRole('button',{name:'OK',exact:true}).click()
    await page.getByRole('menuitem',{name:'Format',exact:true}).click(); await page.getByRole('menuitem',{name:'Style…',exact:true}).click()
    await page.getByRole('option',{name:'Clefs, key & time signatures',exact:true}).click()
    assert.deepEqual(await inputs.evaluateAll(es=>es.map(e=>Number(e.value))),[1.5,1.5])
    const lock = inputs.first().locator('xpath=../..').locator('button').last()
    await lock.click()
    await inputs.last().fill('2'); if(name==='react') await inputs.last().press('Enter'); else await inputs.last().blur()
    assert.deepEqual(await inputs.evaluateAll(es=>es.map(e=>Number(e.value))),[1.5,2])
    await lock.click()
    assert.deepEqual(await inputs.evaluateAll(es=>es.map(e=>Number(e.value))),[1.5,1.5])
    await page.getByRole('radio',{name:'Above staves',exact:true}).check()
    const align=group.locator('.sd-row').filter({has:page.getByText('Alignment with barlines:',{exact:true})}).getByRole('radio')
    await align.nth(1).click()
    assert.equal(await align.nth(1).getAttribute('aria-checked'),'true')
    await page.getByRole('button',{name:'OK',exact:true}).click()
    await page.getByRole('menuitem',{name:'Format',exact:true}).click(); await page.getByRole('menuitem',{name:'Style…',exact:true}).click()
    await page.getByRole('option',{name:'Clefs, key & time signatures',exact:true}).click()
    assert.equal(await page.getByRole('radio',{name:'Above staves',exact:true}).isChecked(),true)
    assert.equal(await align.nth(1).getAttribute('aria-checked'),'true')
    const margin = page.getByRole('radio',{name:'Inset barline',exact:true})
    await margin.check()
    const aboveInputs = name==='react'?group.getByRole('textbox',{name:'Scale:'}):group.locator('input[type=number]').first().locator('..').locator('..').locator('input[type=number]')
    await aboveInputs.first().fill('3.25'); if(name==='react') await aboveInputs.first().press('Enter'); else await aboveInputs.first().blur()
    await group.getByRole('button',{name:'Reset'}).click()
    assert.equal(await margin.isChecked(),false)
    await page.getByRole('radio',{name:'On all staves',exact:true}).check()
    const reset = group.getByRole('button',{name:'Reset'})
    assert.equal(await reset.isEnabled(),true)
    await reset.click()
    assert.deepEqual(await inputs.evaluateAll(es=>es.map(e=>Number(e.value))),[1,1])
    await page.getByRole('radio',{name:'Across staves',exact:true}).check()
    const across=group.locator('.sd-row').filter({has:page.getByText('Alignment across staves:',{exact:true})}).getByRole('radio')
    await across.nth(1).click()
    assert.equal(await across.nth(1).getAttribute('aria-checked'),'true')
    await page.getByRole('button',{name:'OK',exact:true}).click()
    await page.getByRole('menuitem',{name:'Format',exact:true}).click(); await page.getByRole('menuitem',{name:'Style…',exact:true}).click()
    await page.getByRole('option',{name:'Clefs, key & time signatures',exact:true}).click()
    assert.equal(await page.getByRole('radio',{name:'Across staves',exact:true}).isChecked(),true)
    assert.equal(await across.nth(1).getAttribute('aria-checked'),'true')
    console.log(`${name}: scale and alternate alignments persist`)
    await page.close()
  }
} finally {await browser.close()}
